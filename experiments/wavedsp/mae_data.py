"""Waveform-only MAE data and a versioned deterministic preprocessing cache.

Arrays stay contiguous [X,Y,T] in their source dtype on the CPU. Neither peak
files nor labels are needed. Random masks are generated by the training loop.
"""

from __future__ import annotations

import hashlib
import json
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from typing import Any

import blosc2
import numpy as np
import torch
from torch.utils.data import Dataset
from tqdm.auto import tqdm

from experiments.wavedsp.cache import _save_array_atomic, _write_json_atomic

MAE_CACHE_VERSION = 1
MAE_CACHE_KIND = "wavedsp_waveform_only"
CROP_KEYS = ("y_crop_top", "y_crop_bottom", "z_crop_front", "z_crop_back")


def index_digest(entries: list[dict[str, Any]]) -> str:
    return hashlib.sha256(json.dumps(entries, sort_keys=True).encode()).hexdigest()


def preprocessing_settings(
    config: dict[str, Any], target_size: tuple[int, int, int]
) -> dict[str, Any]:
    if len(target_size) != 3 or min(target_size) < 1:
        raise ValueError("target_size must contain positive X,Y,T dimensions")
    crop = {key: int(config.get(key, 0)) for key in CROP_KEYS}
    bins = int(config.get("downsample_z", target_size[2]))
    if min(crop.values()) < 0 or bins != target_size[2]:
        raise ValueError("Nonnegative crops and downsample_z == target_size T required")
    return {
        "target_size": list(target_size),
        "crop": crop,
        "downsample_z": bins,
        "time_sampling": "numpy_linspace_integer_v1",
        "layout": "XYT",
        "dtype": "source",
    }


def resolve_source(path: str, data_root: Path) -> Path:
    source = Path(path)
    if "mae_dataset" in source.parts:
        offset = source.parts.index("mae_dataset") + 1
        source = data_root.joinpath(*source.parts[offset:])
    elif not source.is_absolute():
        source = data_root / source
    resolved = source.resolve()
    if not resolved.is_relative_to(data_root.resolve()):
        raise ValueError(f"Source must be inside data_root: {source}")
    return resolved


def source_directories(config: dict[str, Any], split: str, data_root: Path) -> list[str]:
    if split not in ("train", "valid"):
        raise ValueError(f"Unknown split: {split}")
    paths = config.get(f"{split}_voxel_dirs", [])
    if not paths:
        raise ValueError(f"{split}_voxel_dirs must not be empty")
    return sorted(
        str(resolve_source(path, data_root).relative_to(data_root.resolve())) for path in paths
    )


class MAERawDataset(Dataset):
    def __init__(
        self, config: dict[str, Any], split: str, target_size: tuple[int, int, int], data_root: Path
    ) -> None:
        self.data_root = data_root.resolve(strict=True)
        self.settings = preprocessing_settings(config, target_size)
        self.directories = source_directories(config, split, self.data_root)
        self.entries: list[dict[str, Any]] = []
        seen: set[Path] = set()
        for relative in self.directories:
            directory = self.data_root / relative
            if not directory.is_dir():
                raise FileNotFoundError(f"Missing {split} waveform directory: {directory}")
            files = sorted(directory.rglob("*_voxel.b2"))
            if not files:
                raise ValueError(f"No *_voxel.b2 files in {directory}")
            for path in files:
                resolved = path.resolve()
                if not resolved.is_relative_to(self.data_root):
                    raise ValueError(f"Waveform is outside data_root: {path}")
                if resolved in seen:
                    raise ValueError(f"Duplicate waveform in {split}: {path}")
                seen.add(resolved)
                stat = resolved.stat()
                key = str(resolved.relative_to(self.data_root))
                self.entries.append(
                    {"voxel": key, "sample_id": key, "source": [stat.st_size, stat.st_mtime_ns]}
                )
        self.entries.sort(key=lambda entry: entry["voxel"])

    def __len__(self) -> int:
        return len(self.entries)

    def load_array(self, index: int) -> np.ndarray:
        entry = self.entries[index]
        path = self.data_root / entry["voxel"]
        before = path.stat()
        if [before.st_size, before.st_mtime_ns] != entry["source"]:
            raise ValueError(f"Source changed after indexing: {path}")
        array = blosc2.load_array(path)
        after = path.stat()
        if [after.st_size, after.st_mtime_ns] != entry["source"]:
            raise ValueError(f"Source changed while reading: {path}")
        if array.ndim != 3 or array.dtype.kind not in "uif":
            raise ValueError(f"Expected real numeric [X,Y,T] waveform: {path}")
        crop = self.settings["crop"]
        y_end, t_end = array.shape[1] - crop["y_crop_top"], array.shape[2] - crop["z_crop_back"]
        if crop["y_crop_bottom"] >= y_end or crop["z_crop_front"] >= t_end:
            raise ValueError(f"Crop exceeds waveform shape {array.shape}: {path}")
        array = array[:, crop["y_crop_bottom"] : y_end, crop["z_crop_front"] : t_end]
        bins = self.settings["downsample_z"]
        if array.shape[2] < bins:
            raise ValueError(f"Cannot downsample {array.shape[2]} bins to {bins}: {path}")
        indices = np.linspace(0, array.shape[2] - 1, bins, dtype=int)
        array = np.ascontiguousarray(array[:, :, indices])
        if list(array.shape) != self.settings["target_size"]:
            raise ValueError(
                f"Unexpected preprocessed shape {array.shape}: {path}; "
                f"expected {self.settings['target_size']}"
            )
        return array

    def __getitem__(self, index: int) -> dict[str, Any]:
        return {
            "waveform": torch.from_numpy(self.load_array(index)),
            "sample_id": self.entries[index]["sample_id"],
        }


def check_disjoint(datasets: dict[str, MAERawDataset]) -> None:
    overlap = {e["voxel"] for e in datasets["train"].entries} & {
        e["voxel"] for e in datasets["valid"].entries
    }
    if overlap:
        raise ValueError(f"Train and validation waveforms overlap: {sorted(overlap)[:3]}")


def build_mae_cache(
    config: dict[str, Any],
    target_size: tuple[int, int, int],
    data_root: Path,
    cache_root: Path,
    workers: int = 1,
) -> dict[str, Any]:
    if workers < 1:
        raise ValueError("workers must be at least 1")
    source = data_root.resolve(strict=True)
    destination = cache_root.resolve()
    if (
        destination == source
        or destination.is_relative_to(source)
        or source.is_relative_to(destination)
    ):
        raise ValueError("Cache and raw data directories must be separate, non-nested directories")
    datasets = {
        split: MAERawDataset(config, split, target_size, source) for split in ("train", "valid")
    }
    check_disjoint(datasets)
    settings = preprocessing_settings(config, target_size)
    manifest = {
        "kind": MAE_CACHE_KIND,
        "version": MAE_CACHE_VERSION,
        "source_root": str(source),
        "preprocessing": settings,
        "directories": {s: d.directories for s, d in datasets.items()},
        "entries": {s: d.entries for s, d in datasets.items()},
    }
    fingerprint = hashlib.sha256(json.dumps(manifest, sort_keys=True).encode()).hexdigest()
    state = {"kind": MAE_CACHE_KIND, "version": MAE_CACHE_VERSION, "fingerprint": fingerprint}
    destination.mkdir(parents=True, exist_ok=True)
    state_path, meta_path = destination / "build_state.json", destination / "meta.json"
    if state_path.exists():
        if json.loads(state_path.read_text()) != state:
            raise ValueError("Cache source/configuration changed; use a new cache directory")
    elif any(destination.iterdir()):
        raise ValueError("Nonempty cache without build_state.json; refusing to mix datasets")
    _write_json_atomic(state_path, state)
    # A resumed build is not complete until every indexed file exists again.
    meta_path.unlink(missing_ok=True)
    for split, dataset in datasets.items():

        def process(index: int) -> None:
            path = destination / dataset.entries[index]["voxel"]
            if not path.is_file():
                _save_array_atomic(path, dataset.load_array(index))

        with tqdm(total=len(dataset), desc=f"MAE cache {split}", unit="frame") as bar:
            if workers == 1:
                for index in range(len(dataset)):
                    process(index)
                    bar.update()
            else:
                # Bound queued tasks and decoded arrays even on Python < 3.14.
                with ThreadPoolExecutor(max_workers=workers) as pool:
                    for start in range(0, len(dataset), workers * 2):
                        for _ in pool.map(
                            process, range(start, min(len(dataset), start + workers * 2))
                        ):
                            bar.update()
        if not all((destination / e["voxel"]).is_file() for e in dataset.entries):
            raise RuntimeError(f"Incomplete MAE cache: {split}")
        _write_json_atomic(destination / f"{split}_index.json", dataset.entries)
    meta = {
        **state,
        "complete": True,
        "source_root": str(source),
        "preprocessing": settings,
        "directories": manifest["directories"],
        "index_digests": {
            split: index_digest(dataset.entries) for split, dataset in datasets.items()
        },
        "split_counts": {split: len(dataset) for split, dataset in datasets.items()},
    }
    _write_json_atomic(meta_path, meta)
    return meta


class MAECachedDataset(Dataset):
    def __init__(
        self,
        cache_root: Path,
        split: str,
        config: dict[str, Any],
        target_size: tuple[int, int, int],
        data_root: Path,
    ) -> None:
        self.cache_root = cache_root.resolve()
        meta_path = self.cache_root / "meta.json"
        if not meta_path.is_file():
            raise FileNotFoundError(
                f"Completed MAE cache missing: {meta_path}; run preprocess_mae_cache"
            )
        self.meta = json.loads(meta_path.read_text())
        if (
            self.meta.get("kind") != MAE_CACHE_KIND
            or self.meta.get("version") != MAE_CACHE_VERSION
            or not self.meta.get("complete")
        ):
            raise ValueError("Not a completed waveform-only MAE cache")
        if self.meta.get("preprocessing") != preprocessing_settings(config, target_size):
            raise ValueError("MAE cache preprocessing differs from training configuration")
        if self.meta.get("directories", {}).get(split) != source_directories(
            config, split, data_root
        ):
            raise ValueError("MAE cache split directories differ from training configuration")
        self.entries = json.loads((self.cache_root / f"{split}_index.json").read_text())
        if not self.entries or len(self.entries) != self.meta["split_counts"][split]:
            raise ValueError(f"MAE cache index count mismatch: {split}")
        if index_digest(self.entries) != self.meta.get("index_digests", {}).get(split):
            raise ValueError(f"MAE cache index fingerprint mismatch: {split}")
        for entry in self.entries:
            if not (self.cache_root / entry["voxel"]).resolve().is_relative_to(self.cache_root):
                raise ValueError("Invalid path in MAE cache index")
        self.target_size = target_size

    def __len__(self) -> int:
        return len(self.entries)

    def __getitem__(self, index: int) -> dict[str, Any]:
        entry = self.entries[index]
        array = blosc2.load_array(self.cache_root / entry["voxel"])
        if array.shape != self.target_size or array.dtype.kind not in "uif":
            raise ValueError(f"Invalid cached waveform: {entry['voxel']}")
        return {
            "waveform": torch.from_numpy(np.ascontiguousarray(array)),
            "sample_id": entry["sample_id"],
        }
